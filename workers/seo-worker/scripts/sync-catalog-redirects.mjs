/**
 * Copy catalog slug redirects into this package for Wrangler/tsc (single source:
 * apps/banana-catalog-prototype/catalog-redirects.json).
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const workerRoot = path.join(__dirname, '..')
const source = path.join(workerRoot, '../../apps/banana-catalog-prototype/catalog-redirects.json')
const dest = path.join(workerRoot, 'src/catalogRedirects.generated.ts')

if (!fs.existsSync(source)) {
  console.error(`sync-catalog-redirects: missing ${source}`)
  process.exit(1)
}

const parsed = JSON.parse(fs.readFileSync(source, 'utf8'))
const rows = Array.isArray(parsed?.redirects) ? parsed.redirects : []
const entries = rows
  .filter((entry) => typeof entry?.from === 'string' && typeof entry?.to === 'string')
  .map((entry) => ({
    from: entry.from.trim(),
    to: entry.to.trim(),
    ...(typeof entry.reason === 'string' && entry.reason.trim() ? { reason: entry.reason.trim() } : {}),
  }))

const body = `/** Generated by scripts/sync-catalog-redirects.mjs — do not edit. */
export const CATALOG_REDIRECT_ENTRIES = ${JSON.stringify(entries, null, 2)} as const
`

fs.writeFileSync(dest, body, 'utf8')
console.log(`sync-catalog-redirects: ${source} → ${dest} (${entries.length} entries)`)
